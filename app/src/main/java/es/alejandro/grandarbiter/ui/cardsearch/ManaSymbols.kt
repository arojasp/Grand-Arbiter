/*
 * Mana symbols: Scryfall's official symbol set as vector drawables (ManaSymbolDrawables.kt,
 * generated by tools/cards/build_symbols.py), offline in the APK. Symbols © Wizards of the Coast,
 * used under the Fan Content Policy. A symbol the set doesn't have (an Un-card oddity, or a new
 * symbol arriving with a weekly data update before the app is rebuilt) falls back to a drawn
 * circle with its letter, so text never shows a hole.
 */

private data class SymbolColors(val light: Color, val dark: Color, val text: Color)

private val WHITE_TEXT = Color.White
private val DARK_TEXT = Color(0xFF1A1A1A)

private fun colorsFor(c: Char): SymbolColors = when (c) {
    'W' -> SymbolColors(Color(0xFFFFFDE7), Color(0xFFD9CC8C), DARK_TEXT)
    'U' -> SymbolColors(Color(0xFF90CAF9), Color(0xFF0D47A1), WHITE_TEXT)
    'B' -> SymbolColors(Color(0xFF9E9E9E), Color(0xFF1C1C1C), WHITE_TEXT)
    'R' -> SymbolColors(Color(0xFFFF8A80), Color(0xFFD50000), WHITE_TEXT)   // exact Figma red
    'G' -> SymbolColors(Color(0xFFA5D6A7), Color(0xFF1B5E20), WHITE_TEXT)
    else -> SymbolColors(Color(0xFFEEEEEE), Color(0xFF9E9E9E), DARK_TEXT)   // generic, C, X, T, Q, S…
}

/** "W/U" -> hybrid of W and U; "G/P" -> Phyrexian green; "2/W" -> two-or-white. */
private fun parse(symbol: String): Triple<SymbolColors, SymbolColors?, String> {
    val parts = symbol.uppercase().split('/')
    val colored = parts.filter { it.length == 1 && it[0] in "WUBRG" }
    return when {
        parts.size == 1 -> Triple(colorsFor(parts[0].singleOrNull() ?: '?'), null, parts[0])
        "P" in parts -> Triple(colorsFor(colored.firstOrNull()?.single() ?: 'C'), null, "Φ")
        colored.size == 2 -> Triple(colorsFor(colored[0][0]), colorsFor(colored[1][0]), "")
        else -> Triple(colorsFor(colored.firstOrNull()?.single() ?: 'C'), colorsFor('C'), parts.first { it !in colored })
    }
}

/** One mana symbol filling [modifier]'s size (square box; wide symbols like ∞ are fitted). */
@Composable
fun ManaSymbol(symbol: String, modifier: Modifier = Modifier) {
    val drawable = remember(symbol) { manaDrawable(symbol) }
    if (drawable != null) {
        Image(
            painter = painterResource(drawable),
            contentDescription = null,   // the text around it carries "{R}" as alternate text
            contentScale = ContentScale.Fit,
            modifier = modifier,
        )
    } else {
        DrawnSymbol(symbol, modifier)
    }
}

/** Fallback for symbols missing from the official set. */
@Composable
private fun DrawnSymbol(symbol: String, modifier: Modifier = Modifier) {
    val (first, second, label) = remember(symbol) { parse(symbol) }
    BoxWithConstraints(
        modifier = modifier
            .shadow(1.dp, CircleShape)
            .clip(CircleShape),
        contentAlignment = Alignment.Center,
    ) {
        val px = with(LocalDensity.current) { maxWidth.toPx() }
        val fill = if (second == null) {
            Brush.radialGradient(listOf(first.light, first.dark), center = Offset(px * 0.3f, px * 0.3f), radius = px)
        } else {
            // Hybrid: diagonal split, each half its own color.
            Brush.linearGradient(
                0f to first.dark, 0.5f to first.dark, 0.5f to second.dark, 1f to second.dark,
                start = Offset(0f, 0f), end = Offset(px, px),
            )
        }
        Box(Modifier.fillMaxSize().background(fill))
        if (label.isNotEmpty()) {
            val textColor = if (second != null) WHITE_TEXT else first.text
            val fontSize = with(LocalDensity.current) { (maxWidth * if (label.length > 1) 0.45f else 0.6f).toSp() }
            Text(
                text = label,
                color = textColor,
                textAlign = TextAlign.Center,
                style = TextStyle(
                    fontSize = fontSize,
                    fontWeight = FontWeight.ExtraBold,
                    shadow = if (textColor == WHITE_TEXT) Shadow(Color(0xCC000000), Offset(1f, 1f), 0f) else null,
                ),
            )
        }
    }
}

/** A mana cost as symbols; faces separated by "//". Null-safe for lands (no cost). */
@Composable
fun ManaCostSymbols(cost: String, modifier: Modifier = Modifier, size: Dp = 20.dp) {
    val faces = remember(cost) { CardText.manaCost(cost) }
    Row(
        modifier.semantics(mergeDescendants = true) { contentDescription = cost },
        horizontalArrangement = Arrangement.spacedBy(2.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        faces.forEachIndexed { i, symbols ->
            if (i > 0) Text(" // ", style = MaterialTheme.typography.labelLarge, color = MaterialTheme.colorScheme.onSurfaceVariant)
            symbols.forEach { ManaSymbol(it, Modifier.size(size)) }
        }
    }
}

/** Oracle/ruling text: reminder text in italics, {X} drawn as mana symbols inline. */
@Composable
fun OracleText(text: String, style: TextStyle, color: Color, modifier: Modifier = Modifier) {
    val annotated = remember(text) { CardText.oracle(text, inlineSymbols = true) }
    val inline = remember(text) {
        CardText.symbols(text).associate { symbol ->
            CardText.SYMBOL_PREFIX + symbol to InlineTextContent(
                Placeholder(1.05.em, 1.05.em, PlaceholderVerticalAlign.TextCenter)
            ) { ManaSymbol(symbol, Modifier.fillMaxSize()) }
        }
    }
    Text(annotated, style = style, color = color, inlineContent = inline, modifier = modifier)
}
