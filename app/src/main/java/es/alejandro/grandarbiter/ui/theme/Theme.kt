@Composable
fun GrandArbiterTheme(
    themeMode: ThemeMode,
    textScale: TextScale = TextScale.DEFAULT,
    highContrast: Boolean = false,
    content: @Composable () -> Unit
) {
    val darkTheme = when (themeMode) {
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
    }

    val colorScheme = when {
        darkTheme && highContrast -> DarkHighContrastScheme
        darkTheme -> DarkColorScheme
        highContrast -> LightHighContrastScheme
        else -> LightColorScheme
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            // Edge-to-edge (MainActivity.enableEdgeToEdge): the bars are transparent and the top bars draw
            // behind them. Only the icon color is ours to set; Window.statusBarColor is deprecated and
            // ignored from Android 15.
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }
    // Text size: scale every sp on top of the user's system font size.
    val density = LocalDensity.current
    CompositionLocalProvider(
        LocalDensity provides Density(density.density, density.fontScale * textScale.factor),
        LocalHighContrast provides highContrast,
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}
