#!/usr/bin/env python3
"""
Convert Scryfall's symbol SVGs into Android vector drawables (stdlib only, offline).

Input : cards/source/symbols/symbology.json + svg/*.svg     (python tools/cards/fetch_symbols.py)
Output: app/src/main/res/drawable/mana_<name>.xml            one vector drawable per symbol
        app/src/main/java/.../ui/cardsearch/ManaSymbolDrawables.kt   symbol text -> R.drawable

Supports exactly what Scryfall's SVGs use (checked on 84 files): <svg viewBox>, <g> with fill /
fill-rule / opacity / stroke / translate(), <path d>, <circle>. Anything else FAILS the build
instead of being silently dropped, so a new symbol style can't ship broken.

The symbols belong to Wizards of the Coast, used under the Fan Content Policy (free app + notice).
Usage: python tools/cards/build_symbols.py
"""
from __future__ import annotations

import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fetch_symbols import symbol_file_name  # noqa: E402  (one naming rule for both scripts)

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "cards" / "source" / "symbols"
RES = ROOT / "app" / "src" / "main" / "res" / "drawable"
KT = ROOT / "app" / "src" / "main" / "java" / "es" / "alejandro" / "grandarbiter" / "ui" / "cardsearch" / "ManaSymbolDrawables.kt"
SVG_NS = "{http://www.w3.org/2000/svg}"
HEIGHT_DP = 24
KNOWN_ATTRS = {"svg": {"viewBox", "xmlns"}, "g": {"fill", "fill-rule", "opacity", "stroke", "transform"},
               "path": {"d", "fill", "fill-rule", "id"}, "circle": {"cx", "cy", "r", "fill"}}


class Unsupported(Exception):
    pass


def color(value: str) -> str | None:
    """'#fff' -> '#FFFFFF', 'none' -> None."""
    if value == "none":
        return None
    if not re.fullmatch(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})", value):
        raise Unsupported(f"color {value!r}")
    h = value[1:]
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return "#" + h.upper()


def num(v: float) -> str:
    return f"{v:g}"


def circle_path(cx: float, cy: float, r: float) -> str:
    return f"M{num(cx - r)},{num(cy)}a{num(r)},{num(r)} 0 1,0 {num(2 * r)},0a{num(r)},{num(r)} 0 1,0 {num(-2 * r)},0Z"


def convert(svg_path: Path) -> str:
    root = ET.parse(svg_path).getroot()
    vb = [float(x) for x in root.get("viewBox", "").split()]
    if len(vb) != 4 or vb[0] != 0 or vb[1] != 0:
        raise Unsupported(f"viewBox {root.get('viewBox')!r}")
    w, h = vb[2], vb[3]
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by tools/cards/build_symbols.py from Scryfall's {svg_path.name}. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{num(round(HEIGHT_DP * w / h, 2))}dp"',
        f'    android:height="{HEIGHT_DP}dp"',
        f'    android:viewportWidth="{num(w)}"',
        f'    android:viewportHeight="{num(h)}">',
    ]

    def walk(el, inherited: dict, indent: str):
        tag = el.tag.removeprefix(SVG_NS)
        unknown = set(el.attrib) - KNOWN_ATTRS.get(tag, set())
        if tag not in KNOWN_ATTRS or unknown:
            raise Unsupported(f"<{tag}> {sorted(unknown)}")
        style = dict(inherited)
        for k in ("fill", "fill-rule", "stroke"):
            if k in el.attrib:
                style[k] = el.get(k)
        if "opacity" in el.attrib:
            style["opacity"] = style.get("opacity", 1.0) * float(el.get("opacity"))

        if tag in ("svg", "g"):
            transform = el.get("transform")
            if transform:
                m = re.fullmatch(r"translate\(\s*(-?[\d.]+)[\s,]+(-?[\d.]+)\s*\)", transform)
                if not m:
                    raise Unsupported(f"transform {transform!r}")
                out.append(f'{indent}<group android:translateX="{m[1]}" android:translateY="{m[2]}">')
                for child in el:
                    walk(child, style, indent + "    ")
                out.append(f"{indent}</group>")
            else:
                for child in el:
                    walk(child, style, indent)
            return

        if tag == "circle":
            data = circle_path(float(el.get("cx", 0)), float(el.get("cy", 0)), float(el.get("r")))
        else:
            data = el.get("d")
        fill = color(style.get("fill", "#000"))   # SVG default fill is black
        stroke = color(style["stroke"]) if "stroke" in style else None
        if fill is None and stroke is None:
            return
        attrs = [f'android:pathData="{data}"']
        if fill:
            attrs.append(f'android:fillColor="{fill}"')
            if style.get("fill-rule") == "evenodd":
                attrs.append('android:fillType="evenOdd"')
        if stroke:
            attrs += [f'android:strokeColor="{stroke}"', 'android:strokeWidth="1"']
        if style.get("opacity", 1.0) != 1.0:
            a = num(round(style["opacity"], 3))
            attrs += [f'android:fillAlpha="{a}"'] + ([f'android:strokeAlpha="{a}"'] if stroke else [])
        out.append(f"{indent}<path\n{indent}    " + f"\n{indent}    ".join(attrs) + " />")

    walk(root, {}, "    ")
    out.append("</vector>")
    return "\n".join(out) + "\n"


def main() -> int:
    symbols = json.loads((SRC / "symbology.json").read_text(encoding="utf-8"))["data"]
    RES.mkdir(parents=True, exist_ok=True)
    for old in RES.glob("mana_*.xml"):   # symbols Scryfall removed must not linger
        old.unlink()
    mapping: list[tuple[str, str]] = []
    failed = []
    for s in symbols:
        name = symbol_file_name(s["symbol"])
        svg = SRC / "svg" / f"{name}.svg"
        if not svg.exists():
            continue
        try:
            (RES / f"mana_{name}.xml").write_text(convert(svg), encoding="utf-8", newline="\n")
            mapping.append((s["symbol"].strip("{}"), f"mana_{name}"))
        except (Unsupported, ET.ParseError, ValueError) as e:
            failed.append(f"{s['symbol']}: {e}")
    if failed:
        print("Unsupported SVG content (extend build_symbols.py):\n  " + "\n  ".join(failed), file=sys.stderr)
        return 1

    cases = "\n".join(f'    "{sym.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}" -> R.drawable.{res}'
                      for sym, res in sorted(mapping))
    KT.write_text(f'''package es.alejandro.grandarbiter.ui.cardsearch

import es.alejandro.grandarbiter.R

// Generated by tools/cards/build_symbols.py from Scryfall's /symbology. Do not edit.
// Symbols © Wizards of the Coast, used under the Wizards Fan Content Policy.

/** Drawable for a symbol written without braces ("W", "W/U", "T"), or null if there is none. */
internal fun manaDrawable(symbol: String): Int? = when (symbol) {{
{cases}
    else -> null
}}
''', encoding="utf-8", newline="\n")
    print(f"{len(mapping)} drawables -> {RES.relative_to(ROOT)}/mana_*.xml")
    print(f"mapping -> {KT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
